"""Regenerate the embedded page after editing Disco_ESP/data/index.html."""
from pathlib import Path
root = Path(__file__).resolve().parents[1] / "Disco_ESP"
html = (root / "data/index.html").read_text(encoding="utf-8")
if ')PAGE"' in html:
    raise ValueError("HTML contains the reserved C++ raw string delimiter")
(root / "page.cpp").write_text('extern "C" { extern const char page_html[] = R"PAGE(' + html + ')PAGE"; }\n', encoding="utf-8")
print("page.cpp regenerated")

# App assets remain available even without an SD page or from /recovery.
assets = [("manifest.webmanifest", "application/manifest+json"), ("apple-touch-icon.png", "image/png"), ("icon-192.png", "image/png"), ("icon-512.png", "image/png")]
lines = ["// Generated by tools/embed_web.py. Do not edit.\n#pragma once\n#include <stddef.h>\n"]
for i, (name, mime) in enumerate(assets):
    data = (root / "data" / name).read_bytes()
    lines.append("static const unsigned char web_asset_%d[] = {%s};\n" % (i, ",".join(str(b) for b in data)))
lines.append("static const struct {const char *path; const char *type; const unsigned char *data; size_t size;} web_assets[] = {\n")
for i, (name, mime) in enumerate(assets):
    lines.append('{"/%s","%s",web_asset_%d,sizeof(web_asset_%d)},\n' % (name, mime, i, i))
lines.append("};\n")
(root / "web_assets.h").write_text("".join(lines))
print("web_assets.h regenerated")
